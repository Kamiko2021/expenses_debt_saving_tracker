package com.example.expenses_debt_saving_tracker.util

import android.content.Context
import android.content.Intent
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import com.example.expenses_debt_saving_tracker.model.Debt
import com.example.expenses_debt_saving_tracker.model.Transaction
import com.example.expenses_debt_saving_tracker.model.TransactionType
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.*

object PdfReportGenerator {

    fun generateAndShareReport(context: Context, transactions: List<Transaction>, debts: List<Debt>) {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // A4 Size
        var page = pdfDocument.startPage(pageInfo)
        var canvas = page.canvas
        val paint = Paint()
        val titlePaint = Paint().apply {
            textSize = 20f
            isFakeBoldText = true
            color = Color.BLACK
        }
        val headerPaint = Paint().apply {
            textSize = 14f
            isFakeBoldText = true
            color = Color.DKGRAY
        }
        val textPaint = Paint().apply {
            textSize = 12f
            color = Color.BLACK
        }

        var y = 40f

        // Helper function for disclaimer and footer
        fun drawFooter(c: Canvas, currentY: Float) {
            val footerY = 790f
            val disclaimerPaint = Paint(textPaint).apply { 
                textSize = 10f
                color = Color.GRAY
                typeface = android.graphics.Typeface.create(android.graphics.Typeface.DEFAULT, android.graphics.Typeface.ITALIC)
            }
            c.drawText("This report is for informational purposes only. AI insights are educational and not professional financial advice.", 40f, footerY, disclaimerPaint)
            c.drawText("Generated by Smart Finance Manager - Developed by Karl Michael Lopez", 40f, footerY + 15f, disclaimerPaint)
        }

        fun checkNewPage() {
            if (y > 750) {
                drawFooter(canvas, y)
                pdfDocument.finishPage(page)
                page = pdfDocument.startPage(pageInfo)
                canvas = page.canvas
                y = 40f
            }
        }

        // 1. Header
        canvas.drawText("Financial Report - Expenses & Debt Tracker", 40f, y, titlePaint)
        y += 30f
        canvas.drawText("Generated by: Karl Michael Lopez", 40f, y, textPaint)
        y += 20f
        val sdf = SimpleDateFormat("MMMM dd, yyyy HH:mm", Locale.US)
        canvas.drawText("Date: ${sdf.format(Date())}", 40f, y, textPaint)
        y += 40f

        // 1.5 Financial Summary
        canvas.drawText("Financial Summary", 40f, y, headerPaint)
        y += 25f

        val startOfMonthCal = Calendar.getInstance().apply {
            set(Calendar.DAY_OF_MONTH, 1)
            set(Calendar.HOUR_OF_DAY, 0)
            set(Calendar.MINUTE, 0)
            set(Calendar.SECOND, 0)
            set(Calendar.MILLISECOND, 0)
        }
        val startOfMonthMs = startOfMonthCal.timeInMillis
        val endOfMonthMs = (startOfMonthCal.clone() as Calendar).apply {
            add(Calendar.MONTH, 1)
        }.timeInMillis

        // Real Income (excluding internal deposits, transfers, withdrawals, and loan proceeds)
        val totalIncome = transactions.filter {
            it.type in listOf(TransactionType.INCOME, TransactionType.SALARY) ||
            (it.type == TransactionType.ADJUSTMENT && it.amount > 0)
        }.sumOf { it.amount }

        // Real Expenses (excluding internal transfers, withdrawals, and deposits)
        val totalExpenses = transactions.filter {
            it.type in listOf(TransactionType.EXPENSE, TransactionType.DEBT_PAYMENT, TransactionType.BILL_PAYMENT, TransactionType.SUBSCRIPTION, TransactionType.WIRED_TRANSFER)
        }.sumOf { it.amount }

        // Money Borrowed This Month
        val borrowedFromDebts = debts.filter { debt ->
            val t = debt.startDate.toDate().time
            t >= startOfMonthMs && t < endOfMonthMs
        }.sumOf { if (it.principalAmount > 0) it.principalAmount else it.totalAmount }

        val borrowedFromTxs = transactions.filter { tx ->
            val t = tx.timestamp.toDate().time
            t >= startOfMonthMs && t < endOfMonthMs && (
                tx.type == TransactionType.LOAN_PROCEEDS || (
                    tx.type == TransactionType.INCOME && (
                        tx.category.contains("loan", ignoreCase = true) ||
                        tx.category.contains("borrow", ignoreCase = true) ||
                        tx.description.contains("loan", ignoreCase = true) ||
                        tx.description.contains("borrow", ignoreCase = true)
                    )
                )
            )
        }.sumOf { it.amount }

        val moneyBorrowedThisMonth = maxOf(borrowedFromDebts, borrowedFromTxs)
        val totalSavingsValue = transactions.filter { it.type == TransactionType.SAVINGS }.sumOf { it.amount }
        
        canvas.drawText("Real Inflow (Income/Salary): ${String.format(Locale.US, "₱%,.2f", totalIncome)}", 40f, y, textPaint)
        y += 20f
        canvas.drawText("Real Outflow (Expenses/Debt/Bills): ${String.format(Locale.US, "₱%,.2f", totalExpenses)}", 40f, y, textPaint)
        y += 20f
        canvas.drawText("Money Borrowed This Month: ${String.format(Locale.US, "₱%,.2f", moneyBorrowedThisMonth)}", 40f, y, textPaint)
        y += 20f
        canvas.drawText("Total Savings: ${String.format(Locale.US, "₱%,.2f", totalSavingsValue)}", 40f, y, textPaint)
        y += 20f
        canvas.drawText("Net Balance: ${String.format(Locale.US, "₱%,.2f", totalIncome - totalExpenses - totalSavingsValue)}", 40f, y, textPaint)
        y += 40f

        // 1.7 Balance Breakdown by Source (Pie Chart)
        canvas.drawText("Total Balance Breakdown by Source", 40f, y, headerPaint)
        y += 30f
        
        val balancesBySource = mutableMapOf<String, Double>()
        transactions.forEach { tx ->
            val src = tx.source.ifEmpty { "Cash on Hand" }
            val currentSrcVal = balancesBySource.getOrDefault(src, 0.0)
            
            when(tx.type) {
                TransactionType.INCOME, TransactionType.SALARY, TransactionType.ADJUSTMENT, TransactionType.LOAN_PROCEEDS, TransactionType.CASH_ON_HAND ->
                    balancesBySource[src] = currentSrcVal + tx.amount
                TransactionType.EXPENSE, TransactionType.SAVINGS, 
                TransactionType.DEBT_PAYMENT, TransactionType.BILL_PAYMENT, TransactionType.SUBSCRIPTION, TransactionType.WIRED_TRANSFER ->
                    balancesBySource[src] = currentSrcVal - tx.amount
                TransactionType.TRANSFER -> {
                    balancesBySource[src] = currentSrcVal - tx.amount
                    val dest = tx.destinationSource.ifEmpty { "Cash on Hand" }
                    val currentDestVal = balancesBySource.getOrDefault(dest, 0.0)
                    balancesBySource[dest] = currentDestVal + tx.amount
                }
                TransactionType.WITHDRAWAL -> {
                    balancesBySource[src] = currentSrcVal - tx.amount
                    val dest = tx.destinationSource.ifEmpty { "Cash on Hand" }
                    val currentDestVal = balancesBySource.getOrDefault(dest, 0.0)
                    balancesBySource[dest] = currentDestVal + tx.amount
                }
                TransactionType.DEPOSIT -> {
                    val dest = tx.destinationSource.ifEmpty { src }
                    val cashSrc = if (tx.destinationSource.isNotEmpty()) tx.source.ifEmpty { "Cash on Hand" } else "Cash on Hand"
                    balancesBySource[dest] = balancesBySource.getOrDefault(dest, 0.0) + tx.amount
                    balancesBySource[cashSrc] = balancesBySource.getOrDefault(cashSrc, 0.0) - tx.amount
                }
            }
        }

        val positiveBalances = balancesBySource.filter { it.value > 0 }
        if (positiveBalances.isNotEmpty()) {
            val totalSourceValue = positiveBalances.values.sum()
            val colors = listOf("#1B263B", "#415A77", "#778DA9", "#0D1B2A", "#2D6A4F", "#52B788")
            
            var startAngle = -90f
            val pieRect = android.graphics.RectF(40f, y, 140f, y + 100f)
            
            positiveBalances.entries.toList().forEachIndexed { index, entry ->
                val sweepAngle = ((entry.value / totalSourceValue) * 360f).toFloat()
                paint.color = Color.parseColor(colors[index % colors.size])
                canvas.drawArc(pieRect, startAngle, sweepAngle, true, paint)
                startAngle += sweepAngle
                
                // Draw Legend
                canvas.drawRect(160f, y + (index * 20), 175f, y + (index * 20) + 15, paint)
                canvas.drawText("${entry.key}: ${String.format(Locale.US, "₱%,.2f", entry.value)}", 185f, y + (index * 20) + 12, textPaint)
            }
            y += 120f
        } else {
            canvas.drawText("No balance data available.", 40f, y, textPaint)
            y += 30f
        }
        y += 10f

        // 2. Spending Breakdown by Category (Bar Chart)
        checkNewPage()
        canvas.drawText("Spending Breakdown by Category", 40f, y, headerPaint)
        y += 30f
        
        val expensesByCategory = transactions
            .filter { it.type == TransactionType.EXPENSE }
            .groupBy { it.category }
            .mapValues { it.value.sumOf { t -> t.amount } }
            .toList()
            .sortedByDescending { it.second }

        if (expensesByCategory.isNotEmpty()) {
            val maxAmount = expensesByCategory.maxOf { it.second }.coerceAtLeast(1.0)
            val chartX = 160f
            val chartWidth = 280f
            
            expensesByCategory.forEach { (category, amount) ->
                checkNewPage()
                canvas.drawText(category.take(18), 40f, y + 15, textPaint)
                val barWidth = ((amount / maxAmount) * chartWidth).toFloat()
                
                paint.color = Color.parseColor("#1B263B") // Navy Blue
                canvas.drawRect(chartX, y, chartX + barWidth, y + 20, paint)
                
                canvas.drawText(String.format(Locale.US, "₱%,.2f", amount), chartX + barWidth + 10, y + 15, textPaint)
                y += 35f
            }
        } else {
            canvas.drawText("No expenses recorded yet.", 40f, y, textPaint)
            y += 30f
        }

        y += 20f

        // 2.5 Daily Spending (Last 7 Days)
        checkNewPage()
        canvas.drawText("Daily Spending (Last 7 Days)", 40f, y, headerPaint)
        y += 40f
        
        val dateFormater = SimpleDateFormat("MMM dd", Locale.US)
        val last7DaysList = (0..6).map { i ->
            val cal = Calendar.getInstance()
            cal.add(Calendar.DAY_OF_YEAR, -i)
            dateFormater.format(cal.time)
        }.reversed()

        val spendingMap = transactions
            .filter { it.type == TransactionType.EXPENSE }
            .groupBy { dateFormater.format(it.timestamp.toDate()) }
            .mapValues { it.value.sumOf { t -> t.amount } }

        val spendingByDay = last7DaysList.map { day ->
            day to (spendingMap[day] ?: 0.0)
        }

        if (spendingByDay.any { it.second > 0 }) {
            val maxDaily = spendingByDay.maxOf { it.second }.coerceAtLeast(1.0)
            val chartBaseY = y + 100f
            var chartX = 60f
            val barWidth = 40f
            val spacing = 30f
            
            spendingByDay.forEach { (day, amount) ->
                val barHeight = ((amount / maxDaily) * 80f).toFloat()
                paint.color = Color.parseColor("#1B263B")
                canvas.drawRect(chartX, chartBaseY - barHeight, chartX + barWidth, chartBaseY, paint)
                
                canvas.save()
                canvas.rotate(-45f, chartX, chartBaseY + 15)
                canvas.drawText(day, chartX, chartBaseY + 15, textPaint)
                canvas.restore()
                
                // Draw amount above bar
                val smallTextPaint = Paint(textPaint).apply { textSize = 8f }
                canvas.drawText(String.format(Locale.US, "₱%.0f", amount), chartX, chartBaseY - barHeight - 5, smallTextPaint)
                
                chartX += barWidth + spacing
            }
            y = chartBaseY + 60f
        } else {
            canvas.drawText("No spending data for the last 7 days.", 40f, y, textPaint)
            y += 30f
        }

        y += 20f

        // 2.6 Debt Payment Trends (Last 7 Days)
        checkNewPage()
        canvas.drawText("Debt Payment Trends (Last 7 Days)", 40f, y, headerPaint)
        y += 40f

        val paymentMap = transactions
            .filter { it.type == TransactionType.DEBT_PAYMENT }
            .groupBy { dateFormater.format(it.timestamp.toDate()) }
            .mapValues { it.value.sumOf { t -> t.amount } }

        val paymentsByDay = last7DaysList.map { day ->
            day to (paymentMap[day] ?: 0.0)
        }

        if (paymentsByDay.any { it.second > 0 }) {
            val maxDailyPayment = paymentsByDay.maxOf { it.second }.coerceAtLeast(1.0)
            val chartBaseY = y + 100f
            var chartX = 60f
            val barWidth = 40f
            val spacing = 30f

            paymentsByDay.forEach { (day, amount) ->
                val barHeight = ((amount / maxDailyPayment) * 80f).toFloat()
                paint.color = Color.parseColor("#1B263B")
                canvas.drawRect(chartX, chartBaseY - barHeight, chartX + barWidth, chartBaseY, paint)

                canvas.save()
                canvas.rotate(-45f, chartX, chartBaseY + 15)
                canvas.drawText(day, chartX, chartBaseY + 15, textPaint)
                canvas.restore()

                val smallTextPaint = Paint(textPaint).apply { textSize = 8f }
                canvas.drawText(String.format(Locale.US, "₱%.0f", amount), chartX, chartBaseY - barHeight - 5, smallTextPaint)

                chartX += barWidth + spacing
            }
            y = chartBaseY + 60f
        } else {
            canvas.drawText("No debt payment data for the last 7 days.", 40f, y, textPaint)
            y += 30f
        }

        y += 20f
        
        // 3. Transactions sorted by Date
        checkNewPage()
        canvas.drawText("Recent Transactions (Latest First)", 40f, y, headerPaint)
        y += 25f
        
        // Table Header
        canvas.drawText("Date", 40f, y, textPaint)
        canvas.drawText("Description", 120f, y, textPaint)
        canvas.drawText("Source", 280f, y, textPaint)
        canvas.drawText("Type", 400f, y, textPaint)
        canvas.drawText("Amount", 500f, y, textPaint)
        y += 10f
        canvas.drawLine(40f, y, 560f, y, textPaint)
        y += 20f

        val sortedTxs = transactions.sortedByDescending { it.timestamp }
        val dateSdf = SimpleDateFormat("yyyy-MM-dd", Locale.US)

        sortedTxs.forEach { tx ->
            checkNewPage()
            canvas.drawText(dateSdf.format(tx.timestamp.toDate()), 40f, y, textPaint)
            canvas.drawText(tx.description.take(20), 120f, y, textPaint)
            canvas.drawText(tx.source.take(15), 280f, y, textPaint)
            canvas.drawText(tx.type.name, 400f, y, textPaint)
            canvas.drawText(String.format(Locale.US, "₱%,.2f", tx.amount), 500f, y, textPaint)
            y += 20f
        }

        y += 30f
        
        // 4. Debt Summary & Payments
        checkNewPage()
        canvas.drawText("Active Debts & Installments", 40f, y, headerPaint)
        y += 25f
        
        debts.forEach { debt ->
            checkNewPage()
            canvas.drawText("${debt.name}: ₱${String.format(Locale.US, "%,.2f", debt.remainingAmount)} remaining of ₱${String.format(Locale.US, "%,.2f", debt.totalAmount)}", 40f, y, textPaint)
            y += 18f
            
            // Draw installment status
            val installmentsText = debt.installments.joinToString(" | ") { inst ->
                val status = if (inst.isPaid) "✓" else "✗"
                "M${inst.month}:$status"
            }
            val smallTextPaint = Paint(textPaint).apply { textSize = 10f; color = Color.DKGRAY }
            canvas.drawText("   Installments: $installmentsText", 40f, y, smallTextPaint)
            y += 25f
        }

        y += 20f

        // 5. Disclaimer & Footer
        drawFooter(canvas, y)

        pdfDocument.finishPage(page)

        // Save and Share
        val reportDir = File(context.filesDir, "reports")
        if (!reportDir.exists()) reportDir.mkdirs()
        val file = File(reportDir, "Financial_Report.pdf")
        
        try {
            if (file.exists()) file.delete()
            
            val outputStream = FileOutputStream(file)
            pdfDocument.writeTo(outputStream)
            outputStream.flush()
            outputStream.close()
            
            val uri: Uri = FileProvider.getUriForFile(
                context, 
                "${context.packageName}.provider", 
                file
            )
            
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, uri)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            
            val chooser = Intent.createChooser(intent, "Share Financial Report")
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            context.startActivity(chooser)

        } catch (e: Exception) {
            e.printStackTrace()
        } finally {
            pdfDocument.close()
        }
    }
}
